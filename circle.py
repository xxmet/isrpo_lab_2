import math


def area(r):
    ''' принимает число r - радиус круга, возвращает площадь этого круга
        Пример вызова: area(5) вернёт примерно 78.54. '''
    return math.pi * r * r


def perimeter(r):
    '''принимает число r - радиус круга, возвращает периметр этого круга 
       Пример вызова: perimeter(5) вернёт примерно 31.42. '''
    return 2 * math.pi * r